LONG sys_succeed(const DWORD *arguments) {
    (void)arguments;
    return 0;
}

LONG sys_not_permitted(const DWORD *arguments) {
    (void)arguments;
    return error(LINUX_EPERM);
}

LONG jolt_dispatch(struct jolt_context *context, struct jolt_registers *registers) {
    context->syscall_count++;
    DWORD number = registers->values[7];
    DWORD arguments[6];
    memcpy(arguments, registers->values, sizeof arguments);
    syscall_handler handler = number < SYS_COUNT ? handlers[number] : NULL;
    if (jolt.kernel->trace) trace("> %lu(%lx, %lx, %lx)\r\n", number, arguments[0], arguments[1], arguments[2]);
    LONG result = handler ? handler(arguments) : error(LINUX_ENOSYS);
    if (jolt.kernel->trace)
        trace("%lu(%lx, %lx, %lx, %lx) = %ld\r\n", number, arguments[0], arguments[1], arguments[2], arguments[3], result);
    if (context->exit_requested) return result;
    return deliver_signals(context, result, arguments[0], number);
}
